import ts from "typescript";
import { writeFile, readdir } from "node:fs/promises";
import path from "node:path";
const primitives = (await readdir("packages/ui/primitives")).filter(
  (f) => f.endsWith(".tsx") && f !== "sync-button.tsx",
);
const files = [
  "packages/ui/fields.tsx",
  "packages/ui/choice-select.tsx",
  "packages/ui/query-controls.tsx",
  "packages/ui/collection-view.tsx",
  "packages/ui/collection-view-model.ts",
  "packages/app-ui/record-table.tsx",
  "packages/app-ui/execution-target.tsx",
  "packages/app-ui/download.ts",
  ...primitives.map((f) => "packages/ui/primitives/" + f),
];
const modules = new Map(
  files.map((f) => [
    path.resolve(f),
    f.startsWith("packages/ui/")
      ? "@taskasaur/ui/" + f.slice("packages/ui/".length).replace(/\.tsx?$/, "")
      : "@taskasaur/ui/" + path.basename(f).replace(/\.tsx?$/, ""),
  ]),
);
const config = ts.readConfigFile("tsconfig.json", ts.sys.readFile);
const parsed = ts.parseJsonConfigFileContent(
  config.config,
  ts.sys,
  process.cwd(),
);
const program = ts.createProgram(files, {
  ...parsed.options,
  noEmit: false,
  incremental: false,
  composite: false,
  declaration: true,
  emitDeclarationOnly: true,
  declarationMap: false,
});
const output = [];
program.emit(undefined, (file, text, bom, error, sources) => {
  const source = sources?.[0];
  const module = source && modules.get(path.resolve(source.fileName));
  if (!module) return;
  text = text
    .replace(
      /(?:from\s+|import\()(["'])([^"']+)\1/g,
      (match, quote, specifier) => {
        if (specifier.startsWith("@/ui/"))
          return match.replace(
            specifier,
            specifier.replace("@/ui/", "@taskasaur/ui/"),
          );
        if (!specifier.startsWith(".")) return match;
        if (module.startsWith("@taskasaur/ui/") && specifier === "./runtime")
          return match.replace(specifier, "@taskasaur/plugin-host");
        const absolute = path.resolve(path.dirname(source.fileName), specifier);
        const target =
          modules.get(absolute + ".tsx") ?? modules.get(absolute + ".ts");
        if (!target)
          throw Error(
            `Unmapped UI declaration import: ${source.fileName} -> ${specifier}`,
          );
        return match.replace(specifier, target);
      },
    )
    .replace(/export declare /g, "export ")
    .replace(/^declare /gm, "");
  output.push(`declare module ${JSON.stringify(module)} {\n${text}\n}`);
});
if (output.length !== files.length)
  throw Error("Incomplete shared UI declaration output");
await writeFile(
  "packages/platform/types/ui.d.ts",
  "// Generated by scripts/build-ui-types.mjs from the actual shared UI. Do not hand edit.\n" +
    output.join("\n"),
);
console.log(`Generated ${output.length} shared UI module declarations.`);
